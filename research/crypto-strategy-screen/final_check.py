base = dict(long_only=True, K=20, r3_vt=0.30)
D = P.prepare(ALL)
print("== M9 on 22 coins: yield assumption ==")
for y in (0.0, 0.02, 0.04): P.row(f"M9 yield {y*100:.0f}%", P.simulate(D, **base, cash_yield=y))
print("== M9 on 22 coins: round-trip cost ==")
for c in (0.0006, 0.0015, 0.0030): P.row(f"M9 cost {c*100:.2f}%", P.simulate(D, **base, cost=c))
