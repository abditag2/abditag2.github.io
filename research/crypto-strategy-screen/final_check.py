import portfolio as P, os
ALL = "BTC-USD,ETH-USD,SOL-USD,ADA-USD,DOGE-USD,LINK-USD,AVAX-USD,DOT-USD,LTC-USD,ATOM-USD,BCH-USD,ETC-USD,XLM-USD,XTZ-USD,ALGO-USD,UNI-USD,FIL-USD,AAVE-USD,XRP-USD,ICP-USD,NEAR-USD,APT-USD".split(",")
