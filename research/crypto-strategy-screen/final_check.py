for d in (0, 1, 2): P.row(f"M9 delay {d}h", P.simulate(D, **base, delay=d))
print("== M9 on 22 coins: mix plateau (trend vol target x dip slots) ==")
for vt in (0.25, 0.30, 0.35):
    for K in (15, 20, 25): P.row(f"vt{int(vt*100)} K={K}", P.simulate(D, long_only=True, K=K, r3_vt=vt))
print("== 16 coins never used in any selection (ZRX ... AXS), same fixed configs ==")
D16 = P.prepare(NEW16); print("coins:", D16["coins"])
P.row("M9 vt30 K=20 long-only", P.simulate(D16, **base))
